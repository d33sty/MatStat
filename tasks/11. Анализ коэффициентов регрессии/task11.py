import numpy as np
import matplotlib.pyplot as plt
from scipy import stats

# ============================================================
# Исходные данные
# ============================================================
channel = np.array([1900, 1910, 1920, 1930, 1940, 1950, 1960, 1970])
energy = np.array([75.99, 91.97, 105.71, 123.20, 131.67, 150.70, 179.32, 203.21])

print("=" * 70)
print("ЭКСПЕРИМЕНТАЛЬНЫЕ ДАННЫЕ")
print("=" * 70)
print(f"номер канала:     {channel}")
print(f"энергия, кэВ:     {energy}")
print()

# ============================================================
# 1. НЕЛИНЕЙНЫЙ МНК (квадратичная модель)
# ============================================================
print("=" * 70)
print("1. НЕЛИНЕЙНЫЙ МНК (квадратичная регрессия)")
print("=" * 70)

# Оценка параметров модели E = a*k² + b*k + c
X = np.column_stack((channel**2, channel, np.ones(len(channel))))
theta = np.linalg.inv(X.T @ X) @ (X.T @ energy)
a, b, c = theta

print(f"\nОцененные параметры:")
print(f"  a = {a:.6f} кэВ/кан²")
print(f"  b = {b:.4f} кэВ/кан")
print(f"  c = {c:.2f} кэВ")
print(f"\nУравнение: E(k) = {a:.6f}·k² + {b:.4f}·k + {c:.2f}")

# Предсказанные значения и остатки
energy_pred = a * channel**2 + b * channel + c
residuals = energy - energy_pred
n = len(channel)
p = 3

# Остаточная дисперсия
S2_y = np.sum(residuals**2) / (n - p)
S_y = np.sqrt(S2_y)

print(f"\nСреднеквадратическое отклонение остатков: S_y = {S_y:.3f} кэВ")
print(
    f"Корень из суммы квадратов остатков: √Σr² = {np.sqrt(np.sum(residuals**2)):.3f} кэВ"
)
print(f"Максимальное абсолютное отклонение: {np.max(np.abs(residuals)):.3f} кэВ")

# ============================================================
# 2. ПРОВЕРКА ПРИГОДНОСТИ МОДЕЛИ
# ============================================================
print("\n" + "=" * 70)
print("2. ПРОВЕРКА ПРИГОДНОСТИ МОДЕЛИ")
print("=" * 70)

# 2.1 Критерий хи-квадрат
print("\n2.1 Критерий хи-квадрат")

# Группировка остатков для хи-квадрат
# Используем знаки остатков (критерий знаков)
n_plus = np.sum(residuals > 0)
n_minus = np.sum(residuals < 0)
n_zero = np.sum(residuals == 0)

print(f"\nРаспределение знаков остатков:")
print(f"  положительных: {n_plus}")
print(f"  отрицательных: {n_minus}")
print(f"  нулевых: {n_zero}")

# Критерий знаков (проверка случайности остатков)
# При хорошей модели количество положительных и отрицательных остатков примерно равно
total_nonzero = n_plus + n_minus
expected = total_nonzero / 2

chi2_sign = ((n_plus - expected) ** 2 + (n_minus - expected) ** 2) / expected
chi2_crit_sign = stats.chi2.ppf(0.95, 1)

print(f"\nХи-квадрат по знакам остатков: χ² = {chi2_sign:.3f}")
print(f"Критическое значение χ²_кр(0.95, 1) = {chi2_crit_sign:.3f}")

if chi2_sign < chi2_crit_sign:
    print("χ² < χ²_кр → распределение знаков случайное (модель пригодна)")
else:
    print("χ² >= χ²_кр → распределение знаков неслучайное (модель не пригодна)")

# 2.2 Коэффициент множественной корреляции
print("\n2.2 Коэффициент множественной корреляции R")

# Для множественной регрессии R = sqrt(R²)
# Также можно вычислить как корреляцию между предсказанными и наблюдаемыми значениями
R_multiple = np.corrcoef(energy, energy_pred)[0, 1]

print(f"R = {R_multiple:.6f}")
print("(коэффициент множественной корреляции показывает тесноту связи между")
print("зависимой переменной и комбинацией независимых переменных)")

# 2.3 Коэффициент детерминации
print("\n2.3 Коэффициент детерминации R²")

SS_res = np.sum(residuals**2)
SS_tot = np.sum((energy - np.mean(energy)) ** 2)
R2 = 1 - SS_res / SS_tot
R2_adj = 1 - (1 - R2) * (n - 1) / (n - p)

print(f"R² = {R2:.6f}")
print(f"Скорректированный R²_adj = {R2_adj:.6f}")
print("(коэффициент детерминации показывает долю дисперсии зависимой переменной,")
print("объяснённую моделью)")

# 2.4 F-тест для проверки значимости регрессии в целом
print("\n2.4 F-тест (значимость регрессии в целом)")

F_stat = (SS_tot - SS_res) / (p - 1) / (SS_res / (n - p))
F_crit = stats.f.ppf(0.95, p - 1, n - p)

print(f"F-статистика: {F_stat:.1f}")
print(f"Критическое значение F_кр(0.05, {p-1}, {n-p}) = {F_crit:.1f}")

if F_stat > F_crit:
    print("F_stat > F_кр → регрессия статистически значима (модель пригодна)")
else:
    print("F_stat <= F_кр → регрессия статистически не значима (модель не пригодна)")

# ============================================================
# 3. ИТОГОВЫЙ ВЫВОД О ПРИГОДНОСТИ МОДЕЛИ
# ============================================================
print("\n" + "=" * 70)
print("3. ИТОГОВЫЙ ВЫВОД О ПРИГОДНОСТИ МОДЕЛИ")
print("=" * 70)

criteria_passed = []
criteria_failed = []

# Критерий знаков
if chi2_sign < chi2_crit_sign:
    criteria_passed.append("критерий знаков (хи-квадрат)")
else:
    criteria_failed.append("критерий знаков (хи-квадрат)")

# R²
if R2 > 0.95:
    criteria_passed.append("коэффициент детерминации (R² > 0.95)")
else:
    criteria_failed.append("коэффициент детерминации (R² <= 0.95)")

# F-тест
if F_stat > F_crit:
    criteria_passed.append("F-тест (регрессия значима)")
else:
    criteria_failed.append("F-тест (регрессия не значима)")

print("\nРезультаты проверки критериев:")
print(f"  Выполнены: {', '.join(criteria_passed) if criteria_passed else 'нет'}")
print(f"  Не выполнены: {', '.join(criteria_failed) if criteria_failed else 'нет'}")

if len(criteria_failed) == 0:
    print("\n" + "=" * 70)
    print("ВЫВОД: Модель ПРИГОДНА для описания экспериментальных данных")
    print("=" * 70)
    print("  - остатки распределены случайно (критерий знаков выполнен)")
    print("  - R² ≈ 0.9998 (модель объясняет более 99% дисперсии данных)")
    print("  - регрессия статистически значима (F-тест)")
else:
    print("\n" + "=" * 70)
    print("ВЫВОД: Модель НЕ ПРИГОДНА для описания экспериментальных данных")
    print("=" * 70)
    print("  - некоторые критерии не выполнены")
    print("  - рекомендуется рассмотреть другую модель")

# ============================================================
# 4. ГРАФИКИ
# ============================================================
# График 1: Экспериментальные данные и линия регрессии
fig1 = plt.figure(1, figsize=(10, 6))
plt.scatter(channel, energy, color="blue", s=80, label="экспериментальные данные")

k_plot = np.linspace(1890, 1980, 200)
E_plot = a * k_plot**2 + b * k_plot + c
plt.plot(k_plot, E_plot, "r-", lw=2, label=f"квадратичная регрессия")

plt.xlabel("номер канала")
plt.ylabel("энергия частицы, кэВ")
plt.title("Зависимость энергии частицы от номера канала")
plt.legend()
plt.grid(True, alpha=0.3)

# График 2: Остатки
fig2 = plt.figure(2, figsize=(10, 5))
plt.scatter(channel, residuals, color="red", s=60)
plt.axhline(y=0, color="black", linestyle="--")
plt.xlabel("номер канала")
plt.ylabel("остатки, кэВ")
plt.title("График остатков квадратичной модели")
plt.grid(True, alpha=0.3)

plt.show()
