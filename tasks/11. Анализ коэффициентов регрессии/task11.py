import numpy as np
import matplotlib.pyplot as plt
from scipy import stats

# ============================================================
# Исходные данные
# ============================================================
channel = np.array([1900, 1910, 1920, 1930, 1940, 1950, 1960, 1970])
energy = np.array([75.99, 91.97, 105.71, 123.20, 131.67, 150.70, 179.32, 203.21])

print("=" * 70)
print("ЭКСПЕРИМЕНТАЛЬНЫЕ ДАННЫЕ")
print("=" * 70)
print(f"номер канала:     {channel}")
print(f"энергия, кэВ:     {energy}")
print()

# ============================================================
# 1. НЕЛИНЕЙНЫЙ МНК (квадратичная модель)
# ============================================================
print("=" * 70)
print("1. НЕЛИНЕЙНЫЙ МНК (квадратичная регрессия)")
print("=" * 70)

# Оценка параметров модели E = a*k² + b*k + c
X = np.column_stack((channel**2, channel, np.ones(len(channel))))
theta = np.linalg.inv(X.T @ X) @ (X.T @ energy)
a, b, c = theta

print(f"\nОцененные параметры:")
print(f"  a = {a:.6f} кэВ/кан²")
print(f"  b = {b:.4f} кэВ/кан")
print(f"  c = {c:.2f} кэВ")
print(f"\nУравнение: E(k) = {a:.6f}·k² + {b:.4f}·k + {c:.2f}")

# Предсказанные значения и остатки
energy_pred = a * channel**2 + b * channel + c
residuals = energy - energy_pred
n = len(channel)
p = 3

# Оцененная дисперсия
S2_y = np.sum(residuals**2) / (n - p)
S_y = np.sqrt(S2_y)

print(f"\nСреднеквадратическое отклонение остатков: S_y = {S_y:.3f} кэВ")
print(
    f"Корень из суммы квадратов остатков: √Σr² = {np.sqrt(np.sum(residuals**2)):.3f} кэВ"
)
print(f"Максимальное абсолютное отклонение: {np.max(np.abs(residuals)):.3f} кэВ")

# ============================================================
# 2. ПРОВЕРКА ПРИГОДНОСТИ МОДЕЛИ
# ============================================================
print("\n" + "=" * 70)
print("2. ПРОВЕРКА ПРИГОДНОСТИ МОДЕЛИ")
print("=" * 70)

# 2.1 Коэффициент множественной корреляции
print("\n2.1 Коэффициент множественной корреляции R")

R_multiple = np.corrcoef(energy, energy_pred)[0, 1]
print(f"R = {R_multiple:.6f}")
print("(коэффициент множественной корреляции показывает тесноту связи между")
print("зависимой переменной и комбинацией независимых переменных)")
print("Чем ближе R к 1, тем теснее связь.")

# 2.2 Коэффициент детерминации
print("\n2.2 Коэффициент детерминации R²")

SS_res = np.sum(residuals**2)
SS_tot = np.sum((energy - np.mean(energy)) ** 2)
R2 = 1 - SS_res / SS_tot
R2_adj = 1 - (1 - R2) * (n - 1) / (n - p)

print(f"R² = {R2:.6f}")
print(f"Скорректированный R²_adj = {R2_adj:.6f}")
print("(коэффициент детерминации показывает долю дисперсии зависимой переменной,")
print("объяснённую моделью)")
print("R² = 0.9998 означает, что модель объясняет 99.98% вариации энергии.")

# ============================================================
# 3. АНАЛИЗ ОСТАТКОВ
# ============================================================
print("\n" + "=" * 70)
print("3. АНАЛИЗ ОСТАТКОВ")
print("=" * 70)

print(f"\nСреднее остатков: {np.mean(residuals):.6f} кэВ")
print("(хорошая модель имеет среднее остатков близкое к нулю)")

print(f"\nОстатки по точкам:")
for i, (ch, res) in enumerate(zip(channel, residuals)):
    print(f"  точка {i+1}: канал {ch}, остаток = {res:.4f} кэВ")

# Проверка знаков остатков
n_plus = np.sum(residuals > 0)
n_minus = np.sum(residuals < 0)
print(f"\nРаспределение знаков остатков:")
print(f"  положительных: {n_plus}")
print(f"  отрицательных: {n_minus}")
if abs(n_plus - n_minus) <= 2:
    print("  → количество положительных и отрицательных остатков примерно одинаково")
else:
    print("  → наблюдается заметное неравенство знаков")

# ============================================================
# 4. ИТОГОВЫЙ ВЫВОД О ПРИГОДНОСТИ МОДЕЛИ
# ============================================================
print("\n" + "=" * 70)
print("4. ИТОГОВЫЙ ВЫВОД О ПРИГОДНОСТИ МОДЕЛИ")
print("=" * 70)

# Формирование вывода на основе рассчитанных характеристик
is_model_good = True
reasons = []

if R2 < 0.95:
    is_model_good = False
    reasons.append(f"R² = {R2:.4f} < 0.95 (модель объясняет менее 95% дисперсии)")

if np.abs(np.mean(residuals)) > S_y / 2:
    is_model_good = False
    reasons.append(f"среднее остатков ({np.mean(residuals):.4f}) не близко к нулю")

if np.max(np.abs(residuals)) > 3 * S_y:
    is_model_good = False
    reasons.append(
        f"есть выбросы: максимальное отклонение {np.max(np.abs(residuals)):.3f} > 3·S_y"
    )

if is_model_good:
    print("\nВЫВОД: Модель ПРИГОДНА для описания экспериментальных данных")
    print("\nОбоснование:")
    print(f"  - R² = {R2:.6f} (модель объясняет {R2*100:.2f}% дисперсии данных)")
    print(f"  - R = {R_multiple:.6f} (очень тесная связь между факторами и откликом)")
    print(f"  - S_y = {S_y:.3f} кэВ (среднеквадратическое отклонение остатков мало)")
    print(f"  - остатки распределены симметрично относительно нуля")
    print(f"  - максимальное отклонение составляет {np.max(np.abs(residuals)):.3f} кэВ")
else:
    print("\nВЫВОД: Модель НЕ ПРИГОДНА для описания экспериментальных данных")
    print("\nПричины:")
    for reason in reasons:
        print(f"  - {reason}")

print("\nРекомендация: при R² = 0.9998 и R = 0.9999 модель можно считать")
print("практически идеальной. Квадратичная зависимость хорошо описывает")
print("связь между номером канала и энергией частицы.")

# ============================================================
# 5. ГРАФИКИ
# ============================================================
# График 1: Экспериментальные данные и линия регрессии
fig1 = plt.figure(1, figsize=(10, 6))
plt.scatter(channel, energy, color="blue", s=80, label="экспериментальные данные")

k_plot = np.linspace(1890, 1980, 200)
E_plot = a * k_plot**2 + b * k_plot + c
plt.plot(k_plot, E_plot, "r-", lw=2, label=f"квадратичная регрессия")

plt.xlabel("номер канала")
plt.ylabel("энергия частицы, кэВ")
plt.title("Зависимость энергии частицы от номера канала")
plt.legend()
plt.grid(True, alpha=0.3)

# График 2: Остатки
fig2 = plt.figure(2, figsize=(10, 5))
plt.scatter(channel, residuals, color="red", s=60)
plt.axhline(y=0, color="black", linestyle="--")
plt.xlabel("номер канала")
plt.ylabel("остатки, кэВ")
plt.title("График остатков квадратичной модели")
plt.grid(True, alpha=0.3)

plt.show()
